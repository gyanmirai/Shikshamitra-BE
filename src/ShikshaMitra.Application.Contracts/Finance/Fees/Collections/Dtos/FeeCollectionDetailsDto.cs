using System;
using System.Collections.Generic;

namespace ShikshaMitra.Finance.Fees.Collections.Dtos;

/// <summary>
/// Detailed fee collection information for a specific student fee record,
/// including fee heads breakdown and charge details.
/// </summary>
public class FeeCollectionDetailsDto
{
    public StudentInfoDto Student { get; set; } = default!;
    public FeeSummaryDto Summary { get; set; } = default!;
    public List<FeeHeadDetailDto> FeeHeads { get; set; } = [];
    public List<ChargeDetailDto>? Charges { get; set; }
}

/// <summary>Student identity and enrolment context for a fee collection record.</summary>
public class StudentInfoDto
{
    public Guid StudentId { get; set; }
    public string StudentName { get; set; } = string.Empty;
    public string GrNo { get; set; } = string.Empty;
    public string RollNo { get; set; } = string.Empty;
    public Guid BoardId { get; set; }
    public string BoardName { get; set; } = string.Empty;
    public Guid EducationMediumId { get; set; }
    public string EducationMediumName { get; set; } = string.Empty;
    public Guid StandardId { get; set; }
    public string StandardName { get; set; } = string.Empty;
    public Guid DivisionId { get; set; }
    public string DivisionName { get; set; } = string.Empty;
    public string ContactNo { get; set; } = string.Empty;
    public string Email { get; set; } = string.Empty;
    public string FeeStructureName { get; set; } = string.Empty;
    public bool IsFeeStructureAssigned { get; set; }
}

/// <summary>Aggregated fee payment summary for the academic year.</summary>
public class FeeSummaryDto
{
    public double TotalFee { get; set; }
    public double PaidFee { get; set; }
    public double PendingFee { get; set; }

    /// <summary>
    /// Sum of all DueFee line allocations whose parent <c>FeeRecordMetadata</c> is currently
    /// <c>InReconciliation</c> (cheque/DD submitted but not yet cleared).
    /// </summary>
    public double ReconciliationAmount { get; set; }

    /// <summary>
    /// Total whole-rupee collection amount computed using the whole rupee round-up rule (Ceiling).
    /// </summary>
    public double TotalCollectionAmount { get; set; }

    /// <summary>
    /// Total rounding difference / round-off adjustment across all outstanding obligations.
    /// </summary>
    public double TotalRoundingAdjustment { get; set; }
}

/// <summary>Breakdown of a single fee head including payment status.</summary>
public class FeeHeadDetailDto
{
    public Guid FeeHeadId { get; set; }
    public string FeeHeadName { get; set; } = string.Empty;
    public string CategoryName { get; set; } = string.Empty;
    public double NetAmount { get; set; }
    public double PaidAmount { get; set; }
    public double PendingAmount { get; set; }
    public FeeCollectionStatus Status { get; set; }
    public bool IsSelected { get; set; }
    public bool IsOneTime { get; set; }
    public bool IsOptional { get; set; }

    /// <summary>Additional charges linked to this fee head (currently null — charges are tracked separately).</summary>
    public List<ChargeDetailDto>? Charges { get; set; }
}

/// <summary>Breakdown of a single additional charge including payment status.</summary>
public class ChargeDetailDto
{
    public Guid? IncomeCategoryId { get; set; }
    public Guid? ReceivingBankAccountId { get; set; }
    public string? IncomeCategoryName { get; set; }
    public string? ReceivingBankLabel { get; set; }
    /// <summary>Included paid allocations awaiting instrument clearance; separate from pending balance.</summary>
    public decimal ReconciliationAmount { get; set; }
    public Guid ChargeId { get; set; }
	/// <summary><c>Charge</c> for a Charge Management charge; <c>LateFee</c> for a system-generated late-fee charge.</summary>
	public string SourceType { get; set; } = "Charge";
	/// <summary>The canonical source identifier. For a late-fee charge this is the DueFee id.</summary>
	public Guid SourceId { get; set; }
	/// <summary>True for charges generated by the collection engine rather than Charge Management.</summary>
	public bool IsSystemGenerated { get; set; }
    public string Name { get; set; } = string.Empty;
    public double Amount { get; set; }
    public double PaidAmount { get; set; }
    public double PendingAmount { get; set; }
	public double WaivedAmount { get; set; }
	public bool CanWaive { get; set; }
	public string? Explanation { get; set; }
    public FeeCollectionStatus Status { get; set; }
}

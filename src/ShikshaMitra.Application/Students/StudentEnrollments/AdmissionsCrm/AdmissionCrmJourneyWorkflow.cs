using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading.Tasks;
using Volo.Abp.Application.Services;
using Volo.Abp.DependencyInjection;
using Volo.Abp.Domain.Repositories;

namespace ShikshaMitra.Students.StudentEnrollments.AdmissionsCrm;

public class AdmissionCrmJourneyWorkflow(
	IRepository<AdmissionCrmFollowUpTask, Guid> taskRepository,
	AdmissionCrmMessageDeliveryWorkflow communicationWorkflow,
	AdmissionCrmRegistrationCoordinator registrationCoordinator,
	AdmissionCrmLeadConfigurationReader configuration,
	AdmissionCrmJourneyCandidateReader candidates,
	AdmissionCrmLeadTimelineWriter timeline,
	AdmissionCrmLeadAutomationRecorder recorder,
	AdmissionCrmLeadAccess access) : ApplicationService, ITransientDependency
{
	public async Task<AdmissionCrmJourneyRunResultDto> RunForStaffAsync(
		Guid academicYearId,
		RunAdmissionCrmJourneyRulesDto input)
	{
		await access.EnsureCanAccessAcademicYearAsync(academicYearId, nameof(RunForStaffAsync));
		return await RunCoreAsync(academicYearId, input, enforceUserScope: true);
	}

	public Task<AdmissionCrmJourneyRunResultDto> RunAsync(
		Guid academicYearId,
		RunAdmissionCrmJourneyRulesDto input) =>
		RunCoreAsync(academicYearId, input, enforceUserScope: false);

	public async Task TrySendAcknowledgementAsync(
		Guid leadId,
		Guid? templateId,
		Dictionary<string, string>? variables = null)
	{
		if (!templateId.HasValue)
		{
			return;
		}

		var lead = await access.GetLeadForCurrentTenantAsync(
			leadId,
			nameof(TrySendAcknowledgementAsync),
			enforceScope: false);
		if (await candidates.HasJourneyMessageLogAsync(lead, templateId.Value))
		{
			return;
		}

		try
		{
			await communicationWorkflow.SendFromAutomationAsync(
				lead.Id,
				new SendAdmissionCrmMessageTemplateDto
				{
					TemplateId = templateId.Value,
					Variables = variables ?? new Dictionary<string, string>()
				});
		}
		catch (Exception exception)
		{
			await timeline.AddTimelineEventAsync(
				lead,
				AdmissionCrmTimelineEventType.AutomationFailed,
				"Acknowledgement automation failed",
				$"Default acknowledgement template {templateId.Value} failed: {exception.Message}",
				relatedEntityId: templateId.Value);
		}
	}

	private async Task<AdmissionCrmJourneyRunResultDto> RunCoreAsync(
		Guid academicYearId,
		RunAdmissionCrmJourneyRulesDto input,
		bool enforceUserScope)
	{
		var startedAt = new DateTimeOffset(Clock.Now);
		var cycle = await configuration.GetCycleConfigurationOrDefaultAsync(academicYearId);
		var rules = AdmissionCrmJourneyRuleSerializer.DeserializeRules(cycle.JourneyRulesJson)
			.Where(rule => rule.IsEnabled && rule.Trigger == input.Trigger)
			.OrderBy(rule => rule.Priority)
			.ThenBy(rule => rule.RuleName)
			.ToList();
		var result = new AdmissionCrmJourneyRunResultDto
		{
			Trigger = input.Trigger,
			LeadId = input.LeadId,
			Stage = input.Stage
		};
		if (input.Trigger == AdmissionCrmJourneyTrigger.StageReached && input.Stage.HasValue && input.LeadId.HasValue)
		{
			await registrationCoordinator.IssueApplicableFromAutomationAsync(input.LeadId.Value, input.Stage.Value);
		}

		if (rules.Count == 0)
		{
			return result;
		}

		var leads = await candidates.GetJourneyCandidateLeadsAsync(academicYearId, input, enforceUserScope);
		result.EvaluatedLeadCount = leads.Count;
		if (leads.Count == 0)
		{
			await recorder.RecordJourneyAutomationRunAsync(academicYearId, startedAt, result);
			return result;
		}

		var now = new DateTimeOffset(Clock.Now);
		foreach (var lead in leads)
		{
			foreach (var rule in rules.Where(rule => AdmissionCrmJourneyRuleMatcher.JourneyRuleMatchesLead(rule, lead, input, now)))
			{
				result.MatchedRuleCount++;
				if (rule.CreateTask)
				{
					await CreateTaskAsync(lead, rule, result);
				}

				if (rule.SendMessage && rule.MessageTemplateId.HasValue)
				{
					await SendMessageAsync(lead, rule, result);
				}
			}
		}

		if (result.CreatedTaskCount > 0 || result.FailedActionCount > 0)
		{
			await CurrentUnitOfWork!.SaveChangesAsync();
		}

		await recorder.RecordJourneyAutomationRunAsync(academicYearId, startedAt, result);
		return result;
	}

	private async Task CreateTaskAsync(
		AdmissionInquiryLead lead,
		AdmissionCrmJourneyRuleDto rule,
		AdmissionCrmJourneyRunResultDto result)
	{
		try
		{
			if (await candidates.HasPendingJourneyTaskAsync(lead, rule.TaskTitle!))
			{
				result.SkippedExistingTaskCount++;
				return;
			}

			var task = new AdmissionCrmFollowUpTask(
				GuidGenerator.Create(), CurrentTenant.Id, lead.Id, lead.AcademicYearId,
				rule.TaskTitle!, Clock.Now.AddHours(rule.TaskDueOffsetHours), lead.OwnerUserId,
				rule.TaskNotes ?? $"Generated by admissions CRM journey rule: {rule.RuleName}.");
			await taskRepository.InsertAsync(task, autoSave: false);
			await timeline.AddTimelineEventAsync(
				lead, AdmissionCrmTimelineEventType.TaskCreated, "Journey follow-up task created",
				$"{rule.RuleName}: {task.Title}", relatedEntityId: task.Id, autoSave: false);
			result.CreatedTaskCount++;
		}
		catch (Exception exception)
		{
			await RecordFailureAsync(lead, rule, "task", exception, result);
		}
	}

	private async Task SendMessageAsync(
		AdmissionInquiryLead lead,
		AdmissionCrmJourneyRuleDto rule,
		AdmissionCrmJourneyRunResultDto result)
	{
		try
		{
			if (await candidates.HasJourneyMessageLogAsync(lead, rule.MessageTemplateId!.Value))
			{
				result.SkippedExistingMessageCount++;
				return;
			}

			await communicationWorkflow.SendFromAutomationAsync(
				lead.Id,
				new SendAdmissionCrmMessageTemplateDto
				{
					TemplateId = rule.MessageTemplateId.Value,
					Variables = new Dictionary<string, string> { ["journeyRule"] = rule.RuleName }
				});
			result.SentMessageCount++;
		}
		catch (Exception exception)
		{
			await RecordFailureAsync(lead, rule, "message", exception, result);
		}
	}

	private async Task RecordFailureAsync(
		AdmissionInquiryLead lead,
		AdmissionCrmJourneyRuleDto rule,
		string action,
		Exception exception,
		AdmissionCrmJourneyRunResultDto result)
	{
		result.FailedActionCount++;
		var message = $"{rule.RuleName} {action} failed: {exception.GetBaseException().Message}";
		if (result.FailureMessages.Count < 10)
		{
			result.FailureMessages.Add(message);
		}

		await timeline.AddTimelineEventAsync(
			lead, AdmissionCrmTimelineEventType.AutomationFailed, "Journey automation failed",
			message, relatedEntityId: lead.Id, autoSave: false);
	}
}
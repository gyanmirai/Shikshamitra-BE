	private static string BuildMatchReason(
		AdmissionInquiryLead lead,
		string? normalizedPhone,
		string? normalizedEmail,
		DuplicateProfileProbe profile)
	{
		if (!string.IsNullOrWhiteSpace(normalizedPhone) &&
		    lead.NormalizedPrimaryContactNo == normalizedPhone)
		{
			return "Contact number";
		}

		if (!string.IsNullOrWhiteSpace(normalizedEmail) &&
		    lead.NormalizedEmail == normalizedEmail)
		{
			return "Email";
		}

		if (HasProfileMatch(lead, profile))
		{
			return HasDateOfBirthMatch(lead, profile) && !HasParentGuardianMatch(lead, profile)
				? "Applicant name, date of birth, and desired class"
				: "Applicant name, parent name, and desired class";
		}

		return "Likely duplicate";
	}

	private static bool AreLikelyDuplicates(AdmissionInquiryLead first, AdmissionInquiryLead second)
	{
		return IsLikelyDuplicate(
			second,
			first.NormalizedPrimaryContactNo,
			first.NormalizedEmail,
			DuplicateProfileProbe.FromLead(first));
	}

	private static bool IsLikelyDuplicate(
		AdmissionInquiryLead lead,
		string? normalizedPhone,
		string? normalizedEmail,
		DuplicateProfileProbe profile)
	{
		return
			(!string.IsNullOrWhiteSpace(normalizedPhone) &&
			 lead.NormalizedPrimaryContactNo == normalizedPhone) ||
			(!string.IsNullOrWhiteSpace(normalizedEmail) &&
			 lead.NormalizedEmail == normalizedEmail) ||
			HasProfileMatch(lead, profile);
	}

	private static bool HasProfileMatch(AdmissionInquiryLead lead, DuplicateProfileProbe profile)
	{
		if (!profile.HasMinimumProfile())
		{
			return false;
		}

		if (NormalizeText(lead.FirstName) != profile.FirstName)
		{
			return false;
		}

		if (!AreLastNamesCompatible(lead.LastName, profile.LastName))
		{
			return false;
		}

		if (!HasAdmissionTargetMatch(lead, profile))
		{
			return false;
		}

		return HasParentGuardianMatch(lead, profile) || HasDateOfBirthMatch(lead, profile);
	}

	private static bool HasAdmissionTargetMatch(AdmissionInquiryLead lead, DuplicateProfileProbe profile)
	{
		return
			(profile.TargetStandardId.HasValue && lead.TargetStandardId == profile.TargetStandardId.Value) ||
			(profile.DesiredClassName != null &&
			 NormalizeText(lead.DesiredClassName) == profile.DesiredClassName);
	}

	private static bool HasParentGuardianMatch(AdmissionInquiryLead lead, DuplicateProfileProbe profile)
	{
		return profile.ParentGuardianName != null &&
		       NormalizeText(lead.ParentGuardianName) == profile.ParentGuardianName;
	}

	private static bool HasDateOfBirthMatch(AdmissionInquiryLead lead, DuplicateProfileProbe profile)
	{
		return lead.DateOfBirth.HasValue &&
		       profile.DateOfBirth.HasValue &&
		       lead.DateOfBirth.Value.Date == profile.DateOfBirth.Value.Date;
	}

	private static bool AreLastNamesCompatible(string? leadLastName, string? profileLastName)
	{
		var normalizedLeadLastName = NormalizeText(leadLastName);
		if (normalizedLeadLastName == null || profileLastName == null)
		{
			return true;
		}

		return normalizedLeadLastName == profileLastName;
	}

	private static AdmissionCrmLeadDuplicateDto ToDuplicateDto(
		AdmissionInquiryLead lead,
		string? normalizedPhone,
		string? normalizedEmail,
		DuplicateProfileProbe profile)
	{
		var matchedFields = BuildMatchedFields(lead, normalizedPhone, normalizedEmail, profile);
		return new AdmissionCrmLeadDuplicateDto
		{
			LeadId = lead.Id,
			Stage = lead.Stage,
			FirstName = lead.FirstName,
			LastName = lead.LastName,
			PrimaryContactNo = lead.PrimaryContactNo,
			Email = lead.Email,
			MatchReason = BuildMatchReason(lead, normalizedPhone, normalizedEmail, profile),
			ConfidenceScore = BuildConfidenceScore(matchedFields),
			MatchedFields = matchedFields,
			LastActivityTime = lead.LastActivityTime
		};
	}

	private static IReadOnlyList<string> BuildMatchedFields(
		AdmissionInquiryLead lead,
		string? normalizedPhone,
		string? normalizedEmail,
		DuplicateProfileProbe profile)
	{
		var fields = new List<string>();
		if (!string.IsNullOrWhiteSpace(normalizedPhone) &&
		    lead.NormalizedPrimaryContactNo == normalizedPhone)
		{
			fields.Add("Contact number");
		}

		if (!string.IsNullOrWhiteSpace(normalizedEmail) &&
		    lead.NormalizedEmail == normalizedEmail)
		{
			fields.Add("Email");
		}

		if (HasProfileMatch(lead, profile))
		{
			fields.Add("Applicant name");
			if (HasParentGuardianMatch(lead, profile))
			{
				fields.Add("Parent or guardian");
			}

			if (HasDateOfBirthMatch(lead, profile))
			{
				fields.Add("Date of birth");
			}

			fields.Add(profile.TargetStandardId.HasValue ? "Target standard" : "Desired class");
		}

		return fields;
	}

	private static int BuildConfidenceScore(IReadOnlyCollection<string> matchedFields)
	{
		if (matchedFields.Contains("Contact number"))
		{
			return 100;
		}

		if (matchedFields.Contains("Email"))
		{
			return 95;
		}

		if (matchedFields.Contains("Parent or guardian") &&
		    matchedFields.Contains("Date of birth"))
		{
			return 90;
		}

		if (matchedFields.Contains("Date of birth"))
		{
			return 85;
		}

		if (matchedFields.Contains("Parent or guardian"))
		{
			return 80;
		}

		return 50;
	}

	private static string? NormalizeText(string? value)
	{
		if (string.IsNullOrWhiteSpace(value))
		{
			return null;
		}

		return string.Join(
			" ",
			value
				.Trim()
				.ToLowerInvariant()
				.Split(' ', StringSplitOptions.RemoveEmptyEntries));
	}

	private static IOrderedQueryable<AdmissionInquiryLead> ApplyLeadSorting(
		IQueryable<AdmissionInquiryLead> query,
		string? sorting)
	{
		var descending = sorting?.Contains("desc", StringComparison.OrdinalIgnoreCase) == true;
		var field = sorting?.Split(' ', StringSplitOptions.RemoveEmptyEntries).FirstOrDefault()?.ToLowerInvariant();
		return field switch
		{
			"applicantname" => descending
				? query.OrderByDescending(x => x.FirstName).ThenByDescending(x => x.LastName)
				: query.OrderBy(x => x.FirstName).ThenBy(x => x.LastName),
			"stage" => descending ? query.OrderByDescending(x => x.Stage) : query.OrderBy(x => x.Stage),
			"registrationformnumber" => descending
				? query.OrderByDescending(x => x.RegistrationFormNumber)
				: query.OrderBy(x => x.RegistrationFormNumber),
			"channel" => descending ? query.OrderByDescending(x => x.Channel) : query.OrderBy(x => x.Channel),
			"desiredclassname" => descending
				? query.OrderByDescending(x => x.DesiredClassName)
				: query.OrderBy(x => x.DesiredClassName),
			"intendedroutetype" => descending
				? query.OrderByDescending(x => x.IntendedRouteType)
				: query.OrderBy(x => x.IntendedRouteType),
			"owneruserid" => descending
				? query.OrderByDescending(x => x.OwnerUserId)
				: query.OrderBy(x => x.OwnerUserId),
			"priority" => descending ? query.OrderByDescending(x => x.Priority) : query.OrderBy(x => x.Priority),
			"leadscore" => descending ? query.OrderByDescending(x => x.LeadScore) : query.OrderBy(x => x.LeadScore),
			"lastactivitytime" => descending
				? query.OrderByDescending(x => x.LastActivityTime)
				: query.OrderBy(x => x.LastActivityTime),
			_ => query.OrderByDescending(x => x.LastActivityTime).ThenBy(x => x.Id)
		};
	}

	private static string? NormalizePhone(string? value)
	{
		if (string.IsNullOrWhiteSpace(value))
		{
			return null;
		}

		var digits = new string(value.Where(char.IsDigit).ToArray());
		return string.IsNullOrWhiteSpace(digits) ? null : digits;
	}

	private sealed class DuplicateProfileProbe
	{
		private DuplicateProfileProbe(
			string? firstName,
			string? lastName,
			DateTimeOffset? dateOfBirth,
			string? parentGuardianName,
			Guid? targetStandardId,
			string? desiredClassName)
		{
			FirstName = firstName;
			LastName = lastName;
			DateOfBirth = dateOfBirth;
			ParentGuardianName = parentGuardianName;
			TargetStandardId = targetStandardId;
			DesiredClassName = desiredClassName;
		}

		public string? FirstName { get; }
		public string? LastName { get; }
		public DateTimeOffset? DateOfBirth { get; }
		public string? ParentGuardianName { get; }
		public Guid? TargetStandardId { get; }
		public string? DesiredClassName { get; }

		public static DuplicateProfileProbe FromLead(AdmissionInquiryLead lead)
		{
			return new DuplicateProfileProbe(
				NormalizeText(lead.FirstName),
				NormalizeText(lead.LastName),
				lead.DateOfBirth,
				NormalizeText(lead.ParentGuardianName),
				lead.TargetStandardId,
				NormalizeText(lead.DesiredClassName));
		}

		public static DuplicateProfileProbe FromInput(AdmissionCrmLeadDuplicatePreviewInput input)
		{
			return new DuplicateProfileProbe(
				NormalizeText(input.FirstName),
				NormalizeText(input.LastName),
				input.DateOfBirth,
				NormalizeText(input.ParentGuardianName),
				input.TargetStandardId,
				NormalizeText(input.DesiredClassName));
		}

		public bool HasMinimumProfile()
		{
			return
				FirstName != null &&
				(ParentGuardianName != null || DateOfBirth.HasValue) &&
				(TargetStandardId.HasValue || DesiredClassName != null);
		}
	}

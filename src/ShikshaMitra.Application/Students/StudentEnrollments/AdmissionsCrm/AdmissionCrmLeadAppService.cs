	private async Task<AdmissionCrmJourneyRunResultDto> RunJourneyRulesCoreAsync(
		Guid academicYearId,
		RunAdmissionCrmJourneyRulesDto input)
	{
		var startedAt = new DateTimeOffset(Clock.Now);
		var configuration = await GetCycleConfigurationOrDefaultAsync(academicYearId);
		var rules = AdmissionCrmJourneyRuleSerializer.DeserializeRules(configuration.JourneyRulesJson)
			.Where(x => x.IsEnabled && x.Trigger == input.Trigger)
			.OrderBy(x => x.Priority)
			.ThenBy(x => x.RuleName)
			.ToList();

		var result = new AdmissionCrmJourneyRunResultDto
		{
			Trigger = input.Trigger,
			LeadId = input.LeadId,
			Stage = input.Stage
		};
		if (input.Trigger == AdmissionCrmJourneyTrigger.StageReached && input.Stage.HasValue && input.LeadId.HasValue)
		{
			await _registrationAppService.IssueApplicableFromAutomationAsync(input.LeadId.Value, input.Stage.Value);
		}

		if (rules.Count == 0)
		{
			return result;
		}

		var leads = await GetJourneyCandidateLeadsAsync(academicYearId, input);
		result.EvaluatedLeadCount = leads.Count;
		if (leads.Count == 0)
		{
			await RecordJourneyAutomationRunAsync(academicYearId, startedAt, result);
			return result;
		}

		var now = new DateTimeOffset(Clock.Now);
		foreach (var lead in leads)
		{
			foreach (var rule in rules.Where(rule => JourneyRuleMatchesLead(rule, lead, input, now)))
			{
				result.MatchedRuleCount++;
				if (rule.CreateTask)
				{
					try
					{
						if (await HasPendingJourneyTaskAsync(lead, rule.TaskTitle!))
						{
							result.SkippedExistingTaskCount++;
						}
						else
						{
							var task = new AdmissionCrmFollowUpTask(
								GuidGenerator.Create(),
								CurrentTenant.Id,
								lead.Id,
								lead.AcademicYearId,
								rule.TaskTitle!,
								Clock.Now.AddHours(rule.TaskDueOffsetHours),
								lead.OwnerUserId,
								rule.TaskNotes ?? $"Generated by admissions CRM journey rule: {rule.RuleName}.");
							await _taskRepository.InsertAsync(task, autoSave: false);
							await AddTimelineEventAsync(
								lead,
								AdmissionCrmTimelineEventType.TaskCreated,
								"Journey follow-up task created",
								$"{rule.RuleName}: {task.Title}",
								relatedEntityId: task.Id,
								autoSave: false);
							result.CreatedTaskCount++;
						}
					}
					catch (Exception exception)
					{
						await RecordJourneyFailureAsync(lead, rule, "task", exception, result);
					}
				}

				if (rule.SendMessage && rule.MessageTemplateId.HasValue)
				{
					try
					{
						if (await HasJourneyMessageLogAsync(lead, rule.MessageTemplateId.Value))
						{
							result.SkippedExistingMessageCount++;
						}
						else
						{
							await _communicationAppService.SendTemplateFromAutomationAsync(
								lead.Id,
								new SendAdmissionCrmMessageTemplateDto
								{
									TemplateId = rule.MessageTemplateId.Value,
									Variables = new Dictionary<string, string>
									{
										["journeyRule"] = rule.RuleName
									}
								});
							result.SentMessageCount++;
						}
					}
					catch (Exception exception)
					{
						await RecordJourneyFailureAsync(lead, rule, "message", exception, result);
					}
				}
			}
		}

		if (result.CreatedTaskCount > 0 || result.FailedActionCount > 0)
		{
			await CurrentUnitOfWork!.SaveChangesAsync();
		}

		await RecordJourneyAutomationRunAsync(academicYearId, startedAt, result);
		return result;
	}


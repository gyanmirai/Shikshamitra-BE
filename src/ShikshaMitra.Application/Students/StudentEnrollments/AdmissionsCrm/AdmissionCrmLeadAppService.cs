				input.Notes,
				now);
			await _applicantChecklistProgressRepository.InsertAsync(progress, autoSave: false);
		}
		else
		{
			progress.UpdateStatus(input.Status, input.Notes, now);
			await _applicantChecklistProgressRepository.UpdateAsync(progress, autoSave: false);
		}

		lead.RecordStaffNoteActivity();
		await _leadRepository.UpdateAsync(lead, autoSave: false);
		await AddTimelineEventAsync(
			lead,
			AdmissionCrmTimelineEventType.ApplicantChecklistUpdated,
			"Applicant checklist updated",
			BuildApplicantChecklistTimelineDetails(item, progress),
			relatedEntityId: progress.Id,
			autoSave: false);
		await CurrentUnitOfWork!.SaveChangesAsync();
		return ToApplicantChecklistProgressDto(item, progress, lead);
	}


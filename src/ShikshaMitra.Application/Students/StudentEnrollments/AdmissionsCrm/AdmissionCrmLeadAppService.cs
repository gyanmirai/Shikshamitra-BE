	private async Task<AdmissionCrmStaleArchiveRunResultDto> RunStaleArchiveRulesCoreAsync(Guid academicYearId)
	{
		var configuration = await GetCycleConfigurationOrDefaultAsync(academicYearId);
		var startedAt = new DateTimeOffset(Clock.Now);
		var now = startedAt;
		var staleBefore = now.AddDays(-configuration.StaleAfterDays);
		var archiveBefore = now.AddDays(-configuration.ArchiveAfterDays);

		var queryable = await _leadRepository.GetQueryableAsync();
		var activeLeads = await AsyncExecuter.ToListAsync(queryable.Where(x =>
			x.TenantId == CurrentTenant.Id &&
			x.AcademicYearId == academicYearId &&
			x.Stage != AdmissionInquiryStage.Archived &&
			x.Stage != AdmissionInquiryStage.Eligible &&
			x.Stage != AdmissionInquiryStage.Rejected));
		var candidates = activeLeads
			.Where(x => x.LastActivityTime <= staleBefore)
			.ToList();

		var result = new AdmissionCrmStaleArchiveRunResultDto();
		var markedStaleLeadIds = new List<Guid>();
		var existingPendingStaleTaskLeadIdSet = new HashSet<Guid>();
		if (candidates.Count > 0)
		{
			var candidateLeadIds = candidates.Select(x => x.Id).ToList();
			var taskQueryable = await _taskRepository.GetQueryableAsync();
			var existingPendingStaleTaskLeadIds = await AsyncExecuter.ToListAsync(taskQueryable
				.Where(x =>
					x.TenantId == CurrentTenant.Id &&
					x.AcademicYearId == academicYearId &&
					x.Status == AdmissionCrmTaskStatus.Pending &&
					x.Title == StaleOwnerNotificationTaskTitle &&
					candidateLeadIds.Contains(x.LeadId))
				.Select(x => x.LeadId));
			existingPendingStaleTaskLeadIdSet = existingPendingStaleTaskLeadIds.ToHashSet();
		}

		foreach (var lead in candidates)
		{
			if (lead.Stage == AdmissionInquiryStage.Stale && lead.LastActivityTime <= archiveBefore)
			{
				lead.Archive("Archived by stale lead automation.", Clock.Now);
				await AddTimelineEventAsync(
					lead,
					AdmissionCrmTimelineEventType.Archived,
					"Lead archived by automation",
					"Archived by stale lead automation.",
					relatedEntityId: lead.Id,
					autoSave: false);
				result.ArchivedCount++;
			}
			else if (lead.Stage != AdmissionInquiryStage.Stale)
			{
				lead.MarkStale();
				markedStaleLeadIds.Add(lead.Id);
				await AddTimelineEventAsync(
					lead,
					AdmissionCrmTimelineEventType.MarkedStale,
					"Lead marked stale",
					"Marked stale by inactivity rule.",
					relatedEntityId: lead.Id,
					autoSave: false);
				if (existingPendingStaleTaskLeadIdSet.Contains(lead.Id))
				{
					result.SkippedExistingOwnerNotificationTaskCount++;
				}
				else
				{
					var task = new AdmissionCrmFollowUpTask(
						GuidGenerator.Create(),
						CurrentTenant.Id,
						lead.Id,
						lead.AcademicYearId,
						StaleOwnerNotificationTaskTitle,
						Clock.Now,
						lead.OwnerUserId,
						StaleOwnerNotificationTaskNotes);
					await _taskRepository.InsertAsync(task, autoSave: false);
					await AddTimelineEventAsync(
						lead,
						AdmissionCrmTimelineEventType.TaskCreated,
						"Stale lead follow-up task created",
						task.Title,
						relatedEntityId: task.Id,
						autoSave: false);
					result.CreatedOwnerNotificationTaskCount++;
				}
				result.MarkedStaleCount++;
			}
		}

		if (result.MarkedStaleCount > 0 || result.ArchivedCount > 0)
		{
			await _leadRepository.UpdateManyAsync(candidates, autoSave: true);
		}

		foreach (var leadId in markedStaleLeadIds)
		{
			await RunJourneyRulesCoreAsync(
				academicYearId,
				new RunAdmissionCrmJourneyRulesDto
				{
					Trigger = AdmissionCrmJourneyTrigger.StaleMarked,
					LeadId = leadId,
					Stage = AdmissionInquiryStage.Stale
			});
		}

		await RecordStaleArchiveAutomationRunAsync(academicYearId, startedAt, result);
		return result;
	}


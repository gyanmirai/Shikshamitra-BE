	[Authorize(ShikshaMitraSubmodulePermissions.Students.Enrollment_AdmissionsCrm.ChangeStage)]
	public async Task<AdmissionCrmLeadDto> ChangeStageAsync(Guid leadId, ChangeAdmissionCrmLeadStageDto input)
	{
		var lead = await GetLeadForCurrentTenantAsync(leadId, nameof(ChangeStageAsync));
		var reason = Check.NotNullOrWhiteSpace(
			input.Reason,
			nameof(input.Reason),
			maxLength: AdmissionCrmConsts.MaxNotesLength);
		if (lead.Stage is AdmissionInquiryStage.ExamScheduled
		    or AdmissionInquiryStage.ExamCompleted
		    or AdmissionInquiryStage.Eligible
		    or AdmissionInquiryStage.Waitlisted
		    or AdmissionInquiryStage.Rejected)
		{
			throw new BusinessException("AdmissionCrm:StageManagedByDedicatedWorkflow")
				.WithData("LeadId", lead.Id)
				.WithData("CurrentStage", lead.Stage);
		}

		if (input.Stage is AdmissionInquiryStage.ExamScheduled
		    or AdmissionInquiryStage.ExamCompleted
		    or AdmissionInquiryStage.Eligible
		    or AdmissionInquiryStage.Waitlisted
		    or AdmissionInquiryStage.Rejected
		    or AdmissionInquiryStage.Archived)
		{
			throw new BusinessException("AdmissionCrm:StageManagedByDedicatedWorkflow")
				.WithData("LeadId", lead.Id)
				.WithData("RequestedStage", input.Stage);
		}

		var previousStage = lead.Stage;
		await EnsureConfiguredStageTransitionAllowedAsync(lead, input.Stage);
		lead.ChangeStage(input.Stage);
		await _leadRepository.UpdateAsync(lead, autoSave: true);
		await AddTimelineEventAsync(
			lead,
			AdmissionCrmTimelineEventType.StageChanged,
			"Pipeline stage changed",
			$"{previousStage} -> {input.Stage}. Reason: {reason}",
			relatedEntityId: lead.Id);

		if (previousStage != lead.Stage)
		{
			await RunJourneyRulesCoreAsync(
				lead.AcademicYearId,
				new RunAdmissionCrmJourneyRulesDto
				{
					Trigger = AdmissionCrmJourneyTrigger.StageReached,
					LeadId = lead.Id,
					Stage = lead.Stage
				});
		}

		return ToDto(lead, Array.Empty<AdmissionCrmLeadDuplicateDto>());
	}

	private async Task EnsureConfiguredStageTransitionAllowedAsync(
		AdmissionInquiryLead lead,
		AdmissionInquiryStage requestedStage)
	{
		if (lead.Stage == requestedStage)
		{
			return;
		}

		var queryable = await _stageRepository.GetQueryableAsync();
		var currentStageConfiguration = await AsyncExecuter.FirstOrDefaultAsync(queryable.Where(stage =>
			stage.TenantId == CurrentTenant.Id &&
			stage.AcademicYearId == lead.AcademicYearId &&
			stage.SystemStage == lead.Stage));
		if (string.IsNullOrWhiteSpace(currentStageConfiguration?.AllowedNextStagesJson))
		{
			return;
		}

		var allowedNextStages = DeserializeAllowedNextStages(
			currentStageConfiguration.AllowedNextStagesJson);
		if (allowedNextStages.Contains(requestedStage))
		{
			return;
		}

		throw new BusinessException("AdmissionCrm:StageTransitionNotAllowed")
			.WithData("LeadId", lead.Id)
			.WithData("CurrentStage", lead.Stage)
			.WithData("RequestedStage", requestedStage);
	}

	private static IReadOnlyList<AdmissionInquiryStage> DeserializeAllowedNextStages(
		string allowedNextStagesJson)
	{
		try
		{
			return JsonSerializer.Deserialize<List<AdmissionInquiryStage>>(allowedNextStagesJson)
			       ?? [];
		}
		catch (JsonException)
		{
			return [];
		}
	}

	private async Task<Dictionary<AdmissionInquiryStage, int>> GetStageSlaThresholdsAsync(Guid academicYearId)
	{
		var queryable = await _stageRepository.GetQueryableAsync();
		var stages = await AsyncExecuter.ToListAsync(queryable.Where(stage =>
			stage.TenantId == CurrentTenant.Id &&
			stage.AcademicYearId == academicYearId &&
			stage.SlaTargetHours.HasValue));
		return stages.ToDictionary(
			stage => stage.SystemStage,
			stage => stage.SlaTargetHours!.Value);
	}

	private static int GetSlaThresholdHours(
		AdmissionInquiryStage stage,
		IReadOnlyDictionary<AdmissionInquiryStage, int> stageSlaThresholds,
		int defaultLeadSlaHours)
	{
		return stageSlaThresholds.TryGetValue(stage, out var thresholdHours)
			? thresholdHours
			: defaultLeadSlaHours;
	}


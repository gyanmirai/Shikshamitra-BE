using System;
using System.Collections.Generic;
using System.Linq;
using System.Text.Json;
using System.Threading.Tasks;
using Microsoft.AspNetCore.Authorization;
using ShikshaMitra.Constants.Permissions;
using Volo.Abp;
using Volo.Abp.Application.Services;
using Volo.Abp.DependencyInjection;
using Volo.Abp.Domain.Repositories;

namespace ShikshaMitra.Students.StudentEnrollments.AdmissionsCrm;

public class AdmissionCrmSlaReminderWorkflow(
	IRepository<AdmissionInquiryLead, Guid> leadRepository,
	IRepository<AdmissionCrmFollowUpTask, Guid> taskRepository,
	IRepository<AdmissionCrmSlaHold, Guid> slaHoldRepository,
	StudentScopeAccessService scopeAccess,
	AdmissionCrmLeadConfigurationReader configuration,
	AdmissionCrmLeadTimelineWriter timeline,
	AdmissionCrmLeadAutomationRecorder recorder,
	AdmissionCrmJourneyWorkflow journey) : ApplicationService, ITransientDependency
{
	private const string SlaReminderTaskTitle = "SLA follow-up required";
	private const string SlaReminderTaskNotesPrefix = "Generated by admissions CRM SLA automation";
	private const string SlaEscalationTaskTitle = "SLA escalation required";
	public async Task<AdmissionCrmSlaReminderRunResultDto> RunSlaReminderRulesAsync(Guid academicYearId)
	{
		await scopeAccess.EnsureCanAccessAcademicYearAsync(
			academicYearId,
			nameof(RunSlaReminderRulesAsync));

		return await RunSlaReminderRulesCoreAsync(academicYearId, enforceUserScope: true);
	}

	public async Task<AdmissionCrmSlaReminderRunResultDto> RunSlaReminderRulesFromAutomationAsync(Guid academicYearId)
	{
		return await RunSlaReminderRulesCoreAsync(academicYearId, enforceUserScope: false);
	}

	private async Task<AdmissionCrmSlaReminderRunResultDto> RunSlaReminderRulesCoreAsync(
		Guid academicYearId,
		bool enforceUserScope)
	{
		var cycle = await configuration.GetCycleConfigurationOrDefaultAsync(academicYearId);
		var startedAt = new DateTimeOffset(Clock.Now);
		var now = startedAt;
		var slaCutoff = now.AddHours(-cycle.DefaultLeadSlaHours);
		var result = new AdmissionCrmSlaReminderRunResultDto
		{
			SlaThresholdHours = cycle.DefaultLeadSlaHours,
			SlaCutoff = slaCutoff
		};
		var stageSlaThresholds = await configuration.GetStageSlaThresholdsAsync(academicYearId);
		result.StageOverrideCount = stageSlaThresholds.Count;
		var slaPolicy = JsonSerializer.Deserialize<AdmissionCrmSlaPolicyDto>(cycle.SlaPolicyJson) ?? new AdmissionCrmSlaPolicyDto();
		var minimumThresholdHours = stageSlaThresholds.Values
			.Append(cycle.DefaultLeadSlaHours)
			.Min();
		var earliestCandidateActivity = now.AddHours(-minimumThresholdHours);

		var queryable = await leadRepository.GetQueryableAsync();
		var activeLeadQuery = queryable.Where(x =>
			x.TenantId == CurrentTenant.Id &&
			x.AcademicYearId == academicYearId &&
			x.Stage != AdmissionInquiryStage.Archived &&
			x.Stage != AdmissionInquiryStage.Eligible &&
			x.Stage != AdmissionInquiryStage.Rejected);
		if (enforceUserScope)
		{
			activeLeadQuery = await scopeAccess.ApplyCurrentUserAdmissionLeadScopeAsync(activeLeadQuery);
		}
		var activityCandidates = await AsyncExecuter.ToListAsync(activeLeadQuery.Select(x => new
		{
			x.Id,
			x.LastActivityTime
		}));
		var activityCandidateIds = activityCandidates
			.Where(x => x.LastActivityTime <= earliestCandidateActivity)
			.Select(x => x.Id)
			.ToList();
		var activeLeads = activityCandidateIds.Count == 0
			? []
			: await AsyncExecuter.ToListAsync(activeLeadQuery.Where(x => activityCandidateIds.Contains(x.Id)));
		var activeLeadIds = activeLeads.Select(x => x.Id).ToList();
		var holdQueryable = await slaHoldRepository.GetQueryableAsync();
		List<AdmissionCrmSlaHold> holds = activeLeadIds.Count == 0
			? []
			: await AsyncExecuter.ToListAsync(holdQueryable.Where(x =>
				x.TenantId == CurrentTenant.Id &&
				x.AcademicYearId == academicYearId &&
				activeLeadIds.Contains(x.LeadId)));
		var activeHoldLeadIds = holds.Where(x => x.IsActive).Select(x => x.LeadId).ToHashSet();
		result.PausedLeadCount = activeHoldLeadIds.Count;
		var candidateThresholds = activeLeads
			.Where(lead => !activeHoldLeadIds.Contains(lead.Id))
			.Select(lead => new
			{
				Lead = lead,
				ThresholdHours = AdmissionCrmLeadConfigurationReader.GetSlaThresholdHours(
					lead.Stage,
					stageSlaThresholds,
					cycle.DefaultLeadSlaHours),
				EffectiveHours = CalculateEffectiveSlaHours(lead, now, slaPolicy, holds)
			})
			.Where(x => x.EffectiveHours >= x.ThresholdHours)
			.ToList();
		var candidates = candidateThresholds.Select(x => x.Lead).ToList();
		var thresholdByLeadId = candidateThresholds.ToDictionary(x => x.Lead.Id, x => x.ThresholdHours);
		var escalationLeadIds = candidateThresholds.Where(x => x.EffectiveHours >= x.ThresholdHours + slaPolicy.EscalationAfterHours)
			.Select(x => x.Lead.Id).ToHashSet();

		if (candidates.Count == 0)
		{
			await recorder.RecordSlaReminderAutomationRunAsync(academicYearId, startedAt, result);
			return result;
		}

		var candidateLeadIds = candidates.Select(x => x.Id).ToList();
		var taskQueryable = await taskRepository.GetQueryableAsync();
		var existingPendingSlaLeadIds = await AsyncExecuter.ToListAsync(taskQueryable
			.Where(x =>
				x.TenantId == CurrentTenant.Id &&
				x.AcademicYearId == academicYearId &&
				x.Status == AdmissionCrmTaskStatus.Pending &&
				(x.Title == SlaReminderTaskTitle || x.Title == SlaEscalationTaskTitle) &&
				candidateLeadIds.Contains(x.LeadId))
			.Select(x => x.LeadId));
		var existingPendingSlaLeadIdSet = existingPendingSlaLeadIds.ToHashSet();

		foreach (var lead in candidates)
		{
			if (existingPendingSlaLeadIdSet.Contains(lead.Id))
			{
				result.SkippedExistingTaskCount++;
				continue;
			}

			var escalated = escalationLeadIds.Contains(lead.Id);
			var task = new AdmissionCrmFollowUpTask(
				GuidGenerator.Create(),
				CurrentTenant.Id,
				lead.Id,
				lead.AcademicYearId,
				escalated ? SlaEscalationTaskTitle : SlaReminderTaskTitle,
				Clock.Now,
				escalated ? slaPolicy.EscalationOwnerUserId ?? lead.OwnerUserId : lead.OwnerUserId,
				$"{SlaReminderTaskNotesPrefix} after {thresholdByLeadId[lead.Id]} hours without lead activity in {lead.Stage}.");

			await taskRepository.InsertAsync(task, autoSave: false);
			await timeline.AddTimelineEventAsync(
				lead,
				AdmissionCrmTimelineEventType.TaskCreated,
				"SLA follow-up task created",
				task.Title,
				relatedEntityId: task.Id,
				autoSave: false);
			result.CreatedTaskCount++;
			if (escalated) result.EscalatedTaskCount++;
		}

		if (result.CreatedTaskCount > 0)
		{
			await CurrentUnitOfWork!.SaveChangesAsync();
		}

		foreach (var lead in candidates)
		{
			await journey.RunAsync(
				academicYearId,
				new RunAdmissionCrmJourneyRulesDto
				{
					Trigger = AdmissionCrmJourneyTrigger.SlaMissed,
					LeadId = lead.Id
				});
		}

		await recorder.RecordSlaReminderAutomationRunAsync(academicYearId, startedAt, result);
		return result;
	}

	private static double CalculateEffectiveSlaHours(AdmissionInquiryLead lead, DateTimeOffset now,
		AdmissionCrmSlaPolicyDto policy, IReadOnlyCollection<AdmissionCrmSlaHold> holds)
	{
		var from = lead.LastActivityTime;
		var total = AdmissionCrmSlaClock.CalculateWorkingHours(from, now, policy);
		var held = holds.Where(x => x.LeadId == lead.Id && x.ResumedAt.HasValue && x.ResumedAt.Value > from.UtcDateTime)
			.Sum(x => AdmissionCrmSlaClock.CalculateWorkingHours(
				new DateTimeOffset(x.StartedAt > from.UtcDateTime ? x.StartedAt : from.UtcDateTime, TimeSpan.Zero),
				new DateTimeOffset(x.ResumedAt!.Value < now.UtcDateTime ? x.ResumedAt.Value : now.UtcDateTime, TimeSpan.Zero), policy));
		return Math.Max(0, total - held);
	}
}
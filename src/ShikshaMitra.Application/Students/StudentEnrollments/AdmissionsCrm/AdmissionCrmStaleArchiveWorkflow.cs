using System;
using System.Collections.Generic;
using System.Linq;
using System.Text.Json;
using System.Threading.Tasks;
using Microsoft.AspNetCore.Authorization;
using ShikshaMitra.Constants.Permissions;
using Volo.Abp;
using Volo.Abp.Application.Services;
using Volo.Abp.DependencyInjection;
using Volo.Abp.Domain.Repositories;

namespace ShikshaMitra.Students.StudentEnrollments.AdmissionsCrm;

public class AdmissionCrmStaleArchiveWorkflow(
	IRepository<AdmissionInquiryLead, Guid> leadRepository,
	IRepository<AdmissionCrmFollowUpTask, Guid> taskRepository,
	StudentScopeAccessService scopeAccess,
	AdmissionCrmLeadConfigurationReader configuration,
	AdmissionCrmLeadTimelineWriter timeline,
	AdmissionCrmLeadAutomationRecorder recorder,
	AdmissionCrmJourneyWorkflow journey) : ApplicationService, ITransientDependency
{
	private const string StaleOwnerNotificationTaskTitle = "Stale lead follow-up required";
	private const string StaleOwnerNotificationTaskNotes = "Generated by admissions CRM stale automation when the lead crossed the inactivity threshold.";
	public async Task<AdmissionCrmStaleArchiveRunResultDto> RunStaleArchiveRulesAsync(Guid academicYearId)
	{
		await scopeAccess.EnsureCanAccessAcademicYearAsync(
			academicYearId,
			nameof(RunStaleArchiveRulesAsync));

		return await RunStaleArchiveRulesCoreAsync(academicYearId, enforceUserScope: true);
	}

	public async Task<AdmissionCrmStaleArchiveRunResultDto> RunStaleArchiveRulesFromAutomationAsync(Guid academicYearId)
	{
		return await RunStaleArchiveRulesCoreAsync(academicYearId, enforceUserScope: false);
	}

	private async Task<AdmissionCrmStaleArchiveRunResultDto> RunStaleArchiveRulesCoreAsync(
		Guid academicYearId,
		bool enforceUserScope)
	{
		var cycle = await configuration.GetCycleConfigurationOrDefaultAsync(academicYearId);
		var startedAt = new DateTimeOffset(Clock.Now);
		var now = startedAt;
		var staleBefore = now.AddDays(-cycle.StaleAfterDays);
		var archiveBefore = now.AddDays(-cycle.ArchiveAfterDays);

		var queryable = await leadRepository.GetQueryableAsync();
		var activeLeadQuery = queryable.Where(x =>
			x.TenantId == CurrentTenant.Id &&
			x.AcademicYearId == academicYearId &&
			x.Stage != AdmissionInquiryStage.Archived &&
			x.Stage != AdmissionInquiryStage.Eligible &&
			x.Stage != AdmissionInquiryStage.Rejected);
		if (enforceUserScope)
		{
			activeLeadQuery = await scopeAccess.ApplyCurrentUserAdmissionLeadScopeAsync(activeLeadQuery);
		}
		var activityCandidates = await AsyncExecuter.ToListAsync(activeLeadQuery.Select(x => new
		{
			x.Id,
			x.LastActivityTime
		}));
		var candidateIds = activityCandidates
			.Where(x => x.LastActivityTime <= staleBefore)
			.Select(x => x.Id)
			.ToList();
		var candidates = candidateIds.Count == 0
			? []
			: await AsyncExecuter.ToListAsync(activeLeadQuery.Where(x => candidateIds.Contains(x.Id)));

		var result = new AdmissionCrmStaleArchiveRunResultDto();
		var markedStaleLeadIds = new List<Guid>();
		var existingPendingStaleTaskLeadIdSet = new HashSet<Guid>();
		if (candidates.Count > 0)
		{
			var candidateLeadIds = candidates.Select(x => x.Id).ToList();
			var taskQueryable = await taskRepository.GetQueryableAsync();
			var existingPendingStaleTaskLeadIds = await AsyncExecuter.ToListAsync(taskQueryable
				.Where(x =>
					x.TenantId == CurrentTenant.Id &&
					x.AcademicYearId == academicYearId &&
					x.Status == AdmissionCrmTaskStatus.Pending &&
					x.Title == StaleOwnerNotificationTaskTitle &&
					candidateLeadIds.Contains(x.LeadId))
				.Select(x => x.LeadId));
			existingPendingStaleTaskLeadIdSet = existingPendingStaleTaskLeadIds.ToHashSet();
		}

		foreach (var lead in candidates)
		{
			if (lead.Stage == AdmissionInquiryStage.Stale && lead.LastActivityTime <= archiveBefore)
			{
				lead.Archive("Archived by stale lead automation.", Clock.Now);
				await timeline.AddTimelineEventAsync(
					lead,
					AdmissionCrmTimelineEventType.Archived,
					"Lead archived by automation",
					"Archived by stale lead automation.",
					relatedEntityId: lead.Id,
					autoSave: false);
				result.ArchivedCount++;
			}
			else if (lead.Stage != AdmissionInquiryStage.Stale)
			{
				lead.MarkStale();
				markedStaleLeadIds.Add(lead.Id);
				await timeline.AddTimelineEventAsync(
					lead,
					AdmissionCrmTimelineEventType.MarkedStale,
					"Lead marked stale",
					"Marked stale by inactivity rule.",
					relatedEntityId: lead.Id,
					autoSave: false);
				if (existingPendingStaleTaskLeadIdSet.Contains(lead.Id))
				{
					result.SkippedExistingOwnerNotificationTaskCount++;
				}
				else
				{
					var task = new AdmissionCrmFollowUpTask(
						GuidGenerator.Create(),
						CurrentTenant.Id,
						lead.Id,
						lead.AcademicYearId,
						StaleOwnerNotificationTaskTitle,
						Clock.Now,
						lead.OwnerUserId,
						StaleOwnerNotificationTaskNotes);
					await taskRepository.InsertAsync(task, autoSave: false);
					await timeline.AddTimelineEventAsync(
						lead,
						AdmissionCrmTimelineEventType.TaskCreated,
						"Stale lead follow-up task created",
						task.Title,
						relatedEntityId: task.Id,
						autoSave: false);
					result.CreatedOwnerNotificationTaskCount++;
				}
				result.MarkedStaleCount++;
			}
		}

		if (result.MarkedStaleCount > 0 || result.ArchivedCount > 0)
		{
			await leadRepository.UpdateManyAsync(candidates, autoSave: true);
		}

		foreach (var leadId in markedStaleLeadIds)
		{
			await journey.RunAsync(
				academicYearId,
				new RunAdmissionCrmJourneyRulesDto
				{
					Trigger = AdmissionCrmJourneyTrigger.StaleMarked,
					LeadId = leadId,
					Stage = AdmissionInquiryStage.Stale
				});
		}

		await recorder.RecordStaleArchiveAutomationRunAsync(academicYearId, startedAt, result);
		return result;
	}
}